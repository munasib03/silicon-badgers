#!/usr/bin/env python3
"""Generate the constant tables used by fp_exp.sv.

Rewrites the region between the GENERATED markers in fp_exp.sv and writes a C
header with the same constants for the exhaustive checker.

    pip install gmpy2
    python3 tools/gen_fp_exp_tables.py

All constants are exp() or log() values rounded to nearest at 96 or 128
fractional bits, computed with 400-bit MPFR arithmetic.
"""
import os
import sys

import gmpy2
from gmpy2 import mpfr

gmpy2.get_context().precision = 400

W = 96                  # working fractional bits
HERE = os.path.dirname(os.path.abspath(__file__))
SV_PATH = os.path.join(HERE, '..', 'fp_exp.sv')


def fixed(value, frac_bits):
    return int(gmpy2.rint(value * (mpfr(2) ** frac_bits)))


def tables():
    t1 = [fixed(gmpy2.exp(mpfr(j) / 256), W) for j in range(-128, 128)]
    t2 = [fixed(gmpy2.exp(mpfr(j) / 65536), W) for j in range(256)]
    coeffs = [fixed(mpfr(1) / gmpy2.fac(n), W) for n in range(6)]
    ln2 = fixed(gmpy2.log(mpfr(2)), 128)
    inv_ln2 = fixed(1 / gmpy2.log(mpfr(2)), 32)
    return t1, t2, coeffs, ln2, inv_ln2


def sv_region(t1, t2, coeffs, ln2, inv_ln2):
    out = []
    out.append('  // GENERATED by tools/gen_fp_exp_tables.py -- do not edit by hand.')
    out.append(f"  localparam logic [32:0]  INV_LN2 = 33'h{inv_ln2:x};   // round(2^32 / ln 2)")
    out.append(f"  localparam logic [127:0] LN2     = 128'h{ln2:x};   // round(2^128 * ln 2)")
    for n, c in enumerate(coeffs):
        out.append(f"  localparam logic [96:0]  C{n} = 97'h{c:x};   // round(2^96 / {n}!)")
    out.append('')
    out.append('  // T1[j] = round(2^96 * exp(j / 256)), j = -128..127 indexed by j[7:0]')
    out.append('  function automatic logic [96:0] exp_t1(input logic [7:0] j);')
    out.append('    case (j)')
    for idx, v in enumerate(t1):
        j = idx - 128
        out.append(f"      8'h{j & 0xff:02x}: exp_t1 = 97'h{v:x};")
    out.append("      default: exp_t1 = 97'h0;")
    out.append('    endcase')
    out.append('  endfunction')
    out.append('')
    out.append('  // T2[j] = round(2^96 * exp(j / 65536)), j = 0..255')
    out.append('  function automatic logic [96:0] exp_t2(input logic [7:0] j);')
    out.append('    case (j)')
    for j, v in enumerate(t2):
        out.append(f"      8'h{j:02x}: exp_t2 = 97'h{v:x};")
    out.append("      default: exp_t2 = 97'h0;")
    out.append('    endcase')
    out.append('  endfunction')
    out.append('  // END GENERATED')
    return '\n'.join(out)


def c_header(t1, t2, coeffs, ln2, inv_ln2):
    def hexstr(v):
        return f'"{v:x}"'
    out = ['/* GENERATED by tools/gen_fp_exp_tables.py */']
    out.append(f'static const char *INV_LN2_HEX = {hexstr(inv_ln2)};')
    out.append(f'static const char *LN2_HEX = {hexstr(ln2)};')
    out.append('static const char *C_HEX[6] = {' + ', '.join(hexstr(c) for c in coeffs) + '};')
    out.append('static const char *T1_HEX[256] = {' + ', '.join(hexstr(v) for v in t1) + '};')
    out.append('static const char *T2_HEX[256] = {' + ', '.join(hexstr(v) for v in t2) + '};')
    return '\n'.join(out) + '\n'


def main():
    consts = tables()
    src = open(SV_PATH).read()
    begin = src.index('  // GENERATED by')
    end = src.index('  // END GENERATED') + len('  // END GENERATED')
    src = src[:begin] + sv_region(*consts) + src[end:]
    open(SV_PATH, 'w').write(src)
    if len(sys.argv) > 1:
        open(sys.argv[1], 'w').write(c_header(*consts))


if __name__ == '__main__':
    main()
